$sequenceChoice = $fields['SequenceEditorActions']['values'][0]['Choice'];
$check($dialog($sequenceChoice, 'SequenceEditorActions')['RowColor']['value'] === 0x547CFF, 'Reusable definition restores the exact color and all properties');


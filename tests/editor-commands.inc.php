$run($fields['TimeUpdateRuleButton']['onClick'], $fields, ['TimeEditorActions' => new ArrayIterator([['Choice' => $choice, 'Delay' => 3]])]);
$fields = $form();
$rule = json_decode($fields['YamlInput']['value'], true)['automations'][0];
$check($rule['actions'] === [['type' => 'set', 'target' => ['type' => 'device', 'id' => $device], 'values' => ['color' => ['hex' => '#547CFF'], 'level' => 50, 'state' => 'ON'], 'delay_seconds' => 3]], 'Native apply produces one ordered set action containing all typed values');

$check(!$module->InspectEditorActions(json_encode([['Choice' => $choice, 'Delay' => 0]]), 'edit', 'time'), 'Rights are checked again before using an existing command');
$check(!$module->ChangeEditorCommand('TimeEditorTriggers', $device, '', 'state', json_encode($on)), 'Compound command entry is unavailable to triggers');

$item = $dialog($single);
$run($item['RowActionKind']['onChange'], $item, ['RowActionKind' => 'combined']);
$converted = $module->updates['Choice']['value'];
$check($dialog($converted)['RowCommandSummary']['values'][0]['Value'] === 'On', 'Switching to combined mode preserves the existing property');
$columns = json_decode($module->updates['TimeEditorActions']['columns'], true);
$check(in_array($converted, array_column($columns[0]['edit']['options'], 'value'), true), 'Converted command is offered to native selection validation');
$check($module->ChangeEditorCommand('TimeEditorActions', $device, $converted, (string) $stateVariable, '""', true) && $module->updates['Choice']['value'] === '', 'Removing the last property clears the command');
$check(!$module->InspectEditorActions('[{"Choice":"","Delay":0}]', 'edit', 'time'), 'An empty command cannot become an action');
$module->ConfigureEditorItem('property', 'TimeEditorActions', $device, (string) $colorVariable, '0');
$item = $dialog($module->updates['Choice']['value']);
$run($item['RowColor']['onChange'], $item, ['RowColor' => 0x123456]);
$colorChoice = $module->updates['Choice']['value'];
$check($dialog($colorChoice)['RowColor']['value'] === 0x123456, 'Standalone native color callback round-trips exact RGB');
$module->ConfigureEditorItem('device', 'TimeEditorActions', $device, '', '""', 'eq', 'combined', $choice);
$check($module->updates['Choice']['value'] === '' && json_decode($module->updates['RowCommandSummary']['values'], true) === [], 'Changing the device discards its previous composite command');

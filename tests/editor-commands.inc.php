foreach ([[(string) $levelVariable, '52'], [(string) $levelVariable, '101'], [(string) $colorVariable, '-1'], [(string) $colorVariable, '16777216'], [(string) $tempVariable, '200']] as [$property, $value]) {
    $check(!$module->ChangeEditorCommand('TimeEditorActions', $device, $choice, $property, $value) && $module->updates['Choice']['value'] === $before, 'Bad steps, ranges, colors and conflicting color temperature leave the command intact');
}
